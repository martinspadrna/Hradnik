create or replace function public.hradnik_compute_quality()
returns trigger
language plpgsql
security definer set search_path = public
as $function$
declare n text := lower(coalesce(new.name,'')); score integer := 50; status text := 'needs_review'; reason text := 'Základní kontrola'; bad boolean := false; source_wd text := nullif(trim(coalesce(new.wikidata_id,'')),''); source_web text := nullif(trim(coalesce(new.official_url,'')),'');
begin
  if source_wd is null and new.id is not null then select nullif(trim(coalesce(s.raw_data->>'wikidata_id','')),'') into source_wd from public.hradnik_place_sources s where s.place_id=new.id and coalesce(s.is_active,true)=true and nullif(trim(coalesce(s.raw_data->>'wikidata_id','')),'') is not null order by coalesce(s.confidence,0) desc limit 1; end if;
  if source_web is null and new.id is not null then select nullif(trim(coalesce(s.raw_data->>'official_url','')),'') into source_web from public.hradnik_place_sources s where s.place_id=new.id and coalesce(s.is_active,true)=true and nullif(trim(coalesce(s.raw_data->>'official_url','')),'') is not null order by coalesce(s.confidence,0) desc limit 1; end if;
  if n='' or n ~ '[�]' then bad:=true; reason:='Chybějící nebo rozbité jméno'; end if;
  if n ~ '(úřad městské části|úřad|botanický ústav|nemocnice|poliklinika|základní škola|střední škola|obchodní centrum|supermarket|parkoviště|nádraží)' and n !~ '(hrad|zámek|tvrz|klášter|pevnost|fort|bastion)' then bad:=true; reason:='Pravděpodobně běžná budova nebo instituce'; end if;
  if n in ('hrad','zámek','tvrz','palác','klášter','pevnost','zřícenina','fort','bastion') and source_wd is null and source_web is null then bad:=true; score:=10; reason:='Příliš obecný název bez další identifikace'; end if;
  if source_wd is not null then score:=greatest(score,95); end if;
  if source_web is not null then score:=greatest(score,85); end if;
  if coalesce(new.source_url,'') ~* '(hrady\.cz|hrady-zriceniny\.cz|pamatkovykatalog\.cz)' then score:=greatest(score,88); end if;
  if coalesce(new.character,'') ~* '(castle|chateau|manor|fort|monastery|abbey|zřícen|tvrz|zámek|hrad|klášter)' then score:=greatest(score,60); end if;
  if coalesce(new.latitude,0) between 48 and 52 and coalesce(new.longitude,0) between 12 and 19 then score:=least(100,score+5); end if;
  if coalesce(new.description,'')<>'' or coalesce(new.info_summary,'')<>'' then score:=least(100,score+5); end if;
  if bad then status:='rejected'; score:=least(score,10); else status:=case when score>=90 then 'verified' when score>=75 then 'probable' else 'needs_review' end; end if;
  new.quality_score:=score; new.quality_status:=status; new.quality_reason:=reason; new.quality_checked_at:=now();
  if status='rejected' and coalesce(new.admin_deleted,false)=false then new.is_visible:=false; end if;
  return new;
end;
$function$;

