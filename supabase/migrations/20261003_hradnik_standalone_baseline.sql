create or replace function public.hradnik_normalize_name(p_name text)
returns text
language sql
immutable set search_path = public, extensions
as $function$ select regexp_replace(translate(lower(trim(coalesce(p_name,''))),'áčďéěíňóřšťúůýž','acdeeinorstuuyz'),'[^a-z0-9]+',' ','g'); $function$;

create or replace function public.hradnik_dedupe_key(p_name text)
returns text
language sql
immutable set search_path = public, extensions
as $function$
  select trim(regexp_replace(
    regexp_replace(
      regexp_replace(
        regexp_replace(public.hradnik_normalize_name(coalesce(p_name,'')),
          '^(terenni pozustatky po|pozustatky po)( mozny| mozna| mozne)?[[:space:]]+',' ','i'),
        '(zricenina hradu|zricenina tvrze|zanikly hrad|zanikla tvrz|hrad prestaveny na zamek)$',' ','i'),
      '^(hrad|zamek|zricenina|tvrz|klaster|pevnost|opevnene misto)[[:space:]]+',' ','i'),
    '[[:space:]]+(hrad|zamek|zricenina|tvrz|klaster|pevnost)$',' ','i'));
$function$;

create or replace function public.hradnik_extract_kind_tags(p_character text, p_kind text)
returns text[]
language plpgsql
immutable set search_path = public, extensions
as $function$
declare
  v text := lower(coalesce(p_character,'') || ' ' || coalesce(p_kind,''));
  out text[] := array[]::text[];
begin
  if v like '%zřícen%' or v like '%zricen%' or v like '%ruin%' then out := array_append(out,'Zřícenina'); end if;
  if v like '%tvrz%' or v like '%fort%' then out := array_append(out,'Tvrz'); end if;
  if v like '%klášter%' or v like '%klaster%' or v like '%komenda%' or v like '%monastery%' or v like '%abbey%' then out := array_append(out,'Klášter'); end if;
  if v like '%zámek%' or v like '%zamek%' or v like '%chateau%' or v like '%manor%' then out := array_append(out,'Zámek'); end if;
  if v like '%hrad%' or v like '%castle%' then out := array_append(out,'Hrad'); end if;
  if v like '%opevně%' or v like '%opevnene%' or v like '%bašta%' or v like '%basta%' or v like '%věž%' or v like '%vez%' or v like '%fort%' then out := array_append(out,'Opevněné místo'); end if;
  if coalesce(array_length(out,1),0)=0 and nullif(p_kind,'') is not null then out := array_append(out,p_kind); end if;
  return (select array_agg(distinct x order by x) from unnest(out) x);
end;
$function$;

create or replace function public.hradnik_quality_ok(p text)
returns boolean
language sql
immutable set search_path = public, extensions
as $function$ select coalesce(position(chr(65533) in coalesce(p,''))=0,true); $function$;

create or replace function public.hradnik_force_ruin_kind()
returns trigger
language plpgsql
set search_path = public, extensions
as $function$
declare c text := lower(coalesce(new.character,'')); n text := lower(coalesce(new.name,''));
begin
  if new.kind='Hrad' and (n ~ '(zřícen|zricen|ruin|trosk)' or c ~ '(zřícen|zricen|ruin|trosk)' or c ~ 'castle rem' or c='castle yes' or c ~ 'pozůstatky po .*hradu') then new.kind:='Zřícenina';
  elsif new.kind='Hrad' and (c='tvrz' or c ~ 'hrad/tvrz') then new.kind:='Tvrz';
  elsif new.kind='Hrad' and c ~ 'hrad \(komenda\)' then new.kind:='Klášter';
  elsif new.kind='Hrad' and c ~ 'opevněný kostel' then new.kind:='Opevněné místo';
  elsif new.kind='Hrad' and c ~ '(hrad.*přestavěn.*zámek|přestavěný hrad/zámek)' then new.kind:='Zámek';
  end if;
  return new;
end;
$function$;

create or replace function public.hradnik_quality_guard()
returns trigger
language plpgsql
set search_path = public, extensions
as $function$
declare n text := lower(coalesce(new.name,'')); src text := lower(coalesce(new.source_url,''));
begin
  if new.quality_status is distinct from 'approved' and new.quality_status is distinct from 'manual' then
    if n ~ '(úřad|urad|městský úřad|mestsky urad|ústav|ustav|institut|škola|skola|nemocnice|univerzita|restaurace|hotel|hřiště|hriste|parkoviště|parkoviste|nádraží|nadrazi|stanice|autobus|čerpací stanice|cerpaci stanice)' then
      if src like '%openstreetmap.org%' then new.quality_status:='rejected'; new.quality_reason:='OSM objekt vypadá jako běžná instituce, služba nebo infrastruktura, nikoli historická památka'; new.is_visible:=false; end if;
    end if;
    if src like '%openstreetmap.org%' and coalesce(nullif(trim(new.wikidata_id),''),'')='' and coalesce(nullif(trim(new.official_url),''),'')='' and n !~ '(hrad|zámek|zamek|tvrz|zřícen|zricen|fort|bastion|klášter|klaster|palác|palac|hradiště|hradiste|komenda|opevnění|opevneni|bašta|basta|brána|brana|věž|vez)' then
      new.quality_status:='rejected'; new.quality_reason:='OSM-only objekt bez doplňující identifikace nebo jasného označení historické památky'; new.is_visible:=false;
    end if;
  end if;
  if n ~ '(^|\s)(zámek|zamek)(\s|$)' then new.kind:='Zámek';
  elsif n ~ '(^|\s)tvrz(\s|$)' then new.kind:='Tvrz';
  elsif n ~ '(^|\s)(zřícenina|zricenina)(\s|$)' then new.kind:='Zřícenina';
  elsif n ~ '(^|\s)(klášter|klaster|komenda)(\s|$)' then new.kind:='Klášter';
  elsif n ~ '(^|\s)(fort|bastion|pevnost)(\s|$)' then new.kind:='Opevněné místo'; end if;
  return new;
end;
$function$;

