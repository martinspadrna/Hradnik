create or replace function public.hradnik_ingest_source_records(p_records jsonb)
returns jsonb
language plpgsql
security definer set search_path = public
as $function$
declare
  r jsonb; v_source text; v_external text; v_name text; v_kind text; v_character text;
  v_npu text; v_wikidata text; v_osm text; v_lat double precision; v_lon double precision;
  v_district text; v_region text; v_municipality text; v_description text; v_official text; v_ticket text;
  v_opening jsonb; v_prices jsonb; v_photos jsonb; v_source_url text; v_source_updated timestamptz;
  v_place_id bigint; v_norm text; v_dedupe text; v_tags text[]; v_inserted int:=0; v_updated int:=0; v_linked int:=0; v_skipped int:=0;
begin
  if p_records is null or jsonb_typeof(p_records)<>'array' then return jsonb_build_object('ok',false,'error','p_records must be a JSON array'); end if;
  for r in select value from jsonb_array_elements(p_records) loop
    v_source:=nullif(trim(r->>'source_key'),''); v_external:=nullif(trim(r->>'external_id'),''); v_name:=nullif(trim(r->>'name'),''); v_kind:=nullif(trim(r->>'kind'),''); v_character:=nullif(trim(r->>'character'),'');
    if v_name is null or v_name like '%�%' or coalesce(v_character,'') like '%�%' or coalesce(r->>'description','') like '%�%' then v_skipped:=v_skipped+1; continue; end if;
    v_npu:=nullif(trim(r->>'npu_id'),''); v_wikidata:=nullif(trim(r->>'wikidata_id'),''); v_osm:=nullif(trim(r->>'osm_id'),'');
    v_lat:=case when nullif(r->>'latitude','') is null then null else (r->>'latitude')::double precision end; v_lon:=case when nullif(r->>'longitude','') is null then null else (r->>'longitude')::double precision end;
    v_district:=nullif(trim(r->>'district'),''); v_region:=nullif(trim(r->>'region'),''); v_municipality:=nullif(trim(r->>'municipality'),'');
    v_description:=nullif(trim(r->>'description'),''); v_official:=nullif(trim(r->>'official_url'),''); v_ticket:=nullif(trim(r->>'ticket_url'),'');
    v_opening:=coalesce(r->'opening_hours','{}'::jsonb); v_prices:=coalesce(r->'ticket_prices','{}'::jsonb); v_photos:=coalesce(r->'photo_urls','[]'::jsonb); v_source_url:=nullif(trim(r->>'source_url'),'');
    v_source_updated:=case when nullif(r->>'source_updated_at','') is null then null else (r->>'source_updated_at')::timestamptz end;
    if v_source is null or v_external is null then continue; end if;
    v_norm:=public.hradnik_normalize_name(v_name); v_dedupe:=public.hradnik_dedupe_key(v_name); v_tags:=public.hradnik_extract_kind_tags(v_character,v_kind); v_place_id:=null;
    if v_wikidata is not null then select id into v_place_id from public.hradnik_places where wikidata_id=v_wikidata order by id limit 1; end if;
    if v_place_id is null and v_npu is not null then select id into v_place_id from public.hradnik_places where npu_id=v_npu order by id limit 1; end if;
    if v_place_id is null and v_osm is not null then select id into v_place_id from public.hradnik_places where osm_id=v_osm order by id limit 1; end if;
    if v_place_id is null then select place_id into v_place_id from public.hradnik_place_sources where source_key=v_source and external_id=v_external order by id desc limit 1; end if;
    if v_place_id is null and v_dedupe<>'' then select p.id into v_place_id from public.hradnik_places p where p.is_current and p.dedupe_key=v_dedupe and ((v_district is not null and p.district is not null and public.hradnik_normalize_name(p.district)=public.hradnik_normalize_name(v_district)) or (v_region is not null and p.region is not null and public.hradnik_normalize_name(p.region)=public.hradnik_normalize_name(v_region))) order by (p.wikidata_id is not null) desc,(p.osm_id is not null) desc,p.source_count desc,p.id limit 1; end if;
    if v_place_id is null and v_lat is not null and v_lon is not null then select p.id into v_place_id from public.hradnik_places p where p.is_current and p.dedupe_key=v_dedupe and p.latitude is not null and p.longitude is not null and abs(p.latitude-v_lat)<=0.008 and abs((p.longitude-v_lon)*cos(radians((p.latitude+v_lat)/2)))<=0.012 order by p.source_count desc,p.id limit 1; end if;
    if v_place_id is null then
      insert into public.hradnik_places(canonical_key,source_key,external_id,slug,name,kind,character,district,region,municipality,latitude,longitude,description,official_url,ticket_url,opening_hours,ticket_prices,photo_urls,source_url,source_updated_at,last_verified_at,normalized_name,primary_source_key,source_count,is_visible,is_current,kind_tags,dedupe_key)
