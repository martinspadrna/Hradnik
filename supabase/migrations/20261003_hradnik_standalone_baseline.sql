create or replace function public.hradnik_auto_dedupe()
returns jsonb
language plpgsql
security definer set search_path = public
as $function$
declare r record; merged int:=0; keep_id bigint; drop_id bigint;
begin
  for r in
    select a.id a_id,b.id b_id
    from public.hradnik_places a join public.hradnik_places b on a.id<b.id and a.is_current and b.is_current
      and coalesce(a.dedupe_key,public.hradnik_dedupe_key(a.name))=coalesce(b.dedupe_key,public.hradnik_dedupe_key(b.name))
      and a.latitude is not null and b.latitude is not null and a.longitude is not null and b.longitude is not null
      and abs(a.latitude-b.latitude)<=0.012
      and abs((a.longitude-b.longitude)*cos(radians((a.latitude+b.latitude)/2)))<=0.018
  loop
    begin
      select case when a.source_key='seed' then b.id when b.source_key='seed' then a.id when coalesce(b.source_count,0)>coalesce(a.source_count,0) then b.id when coalesce(a.wikidata_id,'')='' and coalesce(b.wikidata_id,'')<>'' then b.id else a.id end into keep_id from public.hradnik_places a, public.hradnik_places b where a.id=r.a_id and b.id=r.b_id;
      drop_id:=case when keep_id=r.a_id then r.b_id else r.a_id end;
      insert into public.hradnik_place_sources(place_id,source_key,external_id,source_url,source_label,fetched_at,source_updated_at,confidence,raw_data,is_active)
        select keep_id,source_key,external_id,source_url,source_label,fetched_at,source_updated_at,confidence,raw_data,is_active from public.hradnik_place_sources where place_id=drop_id
        on conflict (source_key,external_id) do update set place_id=excluded.place_id,source_url=coalesce(excluded.source_url,public.hradnik_place_sources.source_url),raw_data=coalesce(excluded.raw_data,public.hradnik_place_sources.raw_data),is_active=excluded.is_active;
      delete from public.hradnik_place_sources where place_id=drop_id;
      insert into public.hradnik_user_place_state(user_id,place_id,status,favorite,rating,visited_on,note,updated_at)
        select user_id,keep_id,status,favorite,rating,visited_on,note,updated_at from public.hradnik_user_place_state where place_id=drop_id
        on conflict (user_id,place_id) do update set status=case when excluded.status='visited' or public.hradnik_user_place_state.status='visited' then 'visited' when excluded.status='want' or public.hradnik_user_place_state.status='want' then 'want' else 'none' end,favorite=public.hradnik_user_place_state.favorite or excluded.favorite,rating=greatest(coalesce(public.hradnik_user_place_state.rating,0),coalesce(excluded.rating,0)),visited_on=coalesce(public.hradnik_user_place_state.visited_on,excluded.visited_on),note=coalesce(nullif(public.hradnik_user_place_state.note,''),excluded.note),updated_at=greatest(public.hradnik_user_place_state.updated_at,excluded.updated_at);
      delete from public.hradnik_user_place_state where place_id=drop_id;
      update public.hradnik_places p set npu_id=coalesce(p.npu_id,d.npu_id),wikidata_id=coalesce(p.wikidata_id,d.wikidata_id),osm_id=coalesce(p.osm_id,d.osm_id),latitude=coalesce(p.latitude,d.latitude),longitude=coalesce(p.longitude,d.longitude),municipality=coalesce(p.municipality,d.municipality),district=coalesce(p.district,d.district),region=coalesce(p.region,d.region),description=coalesce(p.description,d.description),official_url=coalesce(p.official_url,d.official_url),ticket_url=coalesce(p.ticket_url,d.ticket_url),photo_urls=case when jsonb_array_length(coalesce(p.photo_urls,'[]'::jsonb))=0 then d.photo_urls else p.photo_urls end,photo_credit=coalesce(p.photo_credit,d.photo_credit),photo_license=coalesce(p.photo_license,d.photo_license),photo_source_url=coalesce(p.photo_source_url,d.photo_source_url),source_count=(select count(*) from public.hradnik_place_sources s where s.place_id=keep_id and s.is_active),updated_at=now() from public.hradnik_places d where p.id=keep_id and d.id=drop_id;
      update public.hradnik_places set is_current=false,is_visible=false,updated_at=now() where id=drop_id;
      merged:=merged+1;
    exception when others then continue; end;
  end loop;
  return jsonb_build_object('merged',merged);
end;
$function$;

